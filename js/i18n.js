let translations = {};

function loadTranslations(lang) {
  translations = TRANSLATIONS[lang] || TRANSLATIONS[DEFAULT_LANG];
}

function updateContent() {
  // Update data-i18n elements (innerHTML allows <strong> tags)
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (translations[key]) {
      el.innerHTML = translations[key];
    }
  });

  // Update data-i18n-html elements (innerHTML)
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const key = el.getAttribute("data-i18n-html");
    if (translations[key]) {
      el.innerHTML = translations[key];
    }
  });

  
  // Update data-i18n-placeholder elements (placeholder)
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (translations[key]) {
      el.placeholder = translations[key];
    }
  });

  // Update CV links
  document.querySelectorAll("[data-i18n-href-en]").forEach(el => {
    const currentLang = document.documentElement.lang;
    const hrefAttr = "data-i18n-href-" + currentLang;
    if (el.hasAttribute(hrefAttr)) {
      el.href = el.getAttribute(hrefAttr);
    }
  });
}

function setLanguage(lang) {
  loadTranslations(lang);
  document.documentElement.lang = lang;
  localStorage.setItem(I18N_STORAGE_KEY, lang);
  updateContent();

  // Update toggle buttons text (show opposite language)
  document.querySelectorAll(".lang-toggle").forEach(btn => {
    btn.textContent = lang === "en" ? "IT" : "EN";
  });
}

function toggleLanguage() {
  const currentLang = document.documentElement.lang || DEFAULT_LANG;
  const newLang = currentLang === "en" ? "it" : "en";
  setLanguage(newLang);
}

document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem(I18N_STORAGE_KEY) || DEFAULT_LANG;
  setLanguage(savedLang);

  document.querySelectorAll(".lang-toggle").forEach(btn => {
    btn.addEventListener("click", toggleLanguage);
  });
});
